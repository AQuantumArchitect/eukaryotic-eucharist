import assert from 'node:assert/strict';
import * as K from '../src/graph_kernel.mjs';

const world = K.createWorld({ seed: 1111 });
let player = K.getPlayer(world);
assert.equal(K.VERSION, 'mobile_v1_1_1_mature_ecosystem_atp_no_starter_acid');
assert.ok(!player.organelles.primitive_acid_pore, 'starter acid pore must be removed');
assert.ok(!K.getAvailableActions(world).some(a => a.id === 'acid'), 'starter acid action must not be available');
assert.ok(K.getAvailableActions(world).some(a => a.id === 'feed'), 'starter feeding exists');
assert.ok(world.entities.filter(e => e.controller === 'algae').length >= 20, 'mature ecosystem seeds many algae');
assert.ok(world.entities.some(e => e.controller === 'algae' && e.fallState === 'sinking'), 'mature ecosystem starts with falling algae');
assert.ok(world.entities.filter(e => e.controller === 'predator').length >= 12, 'mature ecosystem seeds predator layer');
assert.ok(world.fields.length >= 20, 'mature ecosystem starts with rupture fields');
const startEnergy = player.cargo.energy;
const startBiomass = player.cargo.biomass;
for (let i = 0; i < 180; i++) K.step(world, { moveX: 1, moveY: 0, aimX: 1, aimY: 0 }, 1 / 60);
player = K.getPlayer(world);
assert.ok(player.cargo.energy < startEnergy || player.cargo.biomass < startBiomass, 'movement/upkeep/fermentation should change ATP economy');

player.cargo.biomass = 200;
player.cargo.lipids = 200;
player.cargo.energy = 100;
player.cargo.toxins = 100;
player.cargo.spores = 20;
player.cargo.enzymes = 20;
player.cargo.crystals = 20;
player.cargo.vacuoles = 20;
let buy = K.buyOffering(world, 'fermentation_matrix');
assert.equal(buy.ok, true, 'fermentation matrix should be buyable');
buy = K.buyOffering(world, 'storage_vacuole');
assert.equal(buy.ok, true, 'storage vacuole should be buyable');
buy = K.buyOffering(world, 'exotic_vacuole');
assert.equal(buy.ok, true, 'exotic vesicle rack should be buyable');
buy = K.buyOffering(world, 'lance_bristle');
assert.equal(buy.ok, true, 'lance bristle should be buyable');
buy = K.buyOffering(world, 'toxin_sac');
assert.equal(buy.ok, true, 'toxin sac should be buyable as late Tier 2 acid gate');
player = K.getPlayer(world);
assert.ok(player.organelles.fermentation_matrix >= 1, 'fermentation organ installed');
assert.ok(player.organelles.storage_vacuole >= 1, 'storage organ installed');
assert.ok(player.organelles.exotic_vacuole >= 1, 'exotic storage organ installed');
assert.ok(player.organelles.lance_bristle >= 1, 'lance organ installed');
assert.ok(player.organelles.toxin_sac >= 1, 'toxin sac installed');
assert.ok(K.getAvailableActions(world).some(a => a.id === 'acid'), 'acid action appears only after toxin sac');
const hud = K.getHudProjection(world);
assert.ok(hud.resources.find(r => r.id === 'biomass').max > 150, 'storage vacuole expands biomass cap');
assert.ok(hud.resources.find(r => r.id === 'spores').max > 32, 'exotic rack expands spore cap');
assert.ok(hud.metabolism.fermentationLevel >= 1, 'HUD exposes fermentation level');

for (let i = 0; i < 240; i++) K.step(world, { moveX: 0, moveY: 0, aimX: 1, aimY: 0 }, 1 / 60);
assert.ok(world.entities.length > 20, 'mature simulation remains populated');
console.log('MOBILE_V1_1_1_ATP_MATURE_ECOSYSTEM_NO_STARTER_ACID_SMOKE_OK');
