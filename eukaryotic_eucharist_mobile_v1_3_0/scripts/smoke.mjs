import * as K from '../src/graph_kernel.mjs';

function assert(cond, msg) {
  if (!cond) throw new Error(msg);
}
function res(hud, id) {
  return hud.resources.find(r => r.id === id);
}

const world = K.createWorld({ seed: 1300 });
assert(K.VERSION.includes('v1_3_0'), 'version should be v1.3.0');
let player = K.getPlayer(world);
assert(player.organelles.membrane === 1, 'starter has membrane container');
assert(player.organelles.membrane_intake === 1, 'starter feeding is an organelle');
assert(player.organelles.anaerobic_processor === 1, 'starter ATP generation is an organelle');
assert(player.organelles.basal_motility === 1, 'starter movement is an organelle');
assert(!player.organelles.toxin_launcher, 'starter has no toxic launcher');
assert(!player.organelles.rasping_lamella, 'starter has no rasping lamella');
assert(world.entities.length > 45 && world.fields.length > 10, 'mature ecology seeded');

const caps0 = K.__test.caps(player);
assert(caps0.spores === 1 && caps0.enzymes === 1 && caps0.crystals === 1, 'base exotic capacity is one each');
player.organelles.exotic_vacuole = 2;
const caps1 = K.__test.caps(player);
assert(caps1.spores > caps0.spores && caps1.enzymes > caps0.enzymes && caps1.crystals > caps0.crystals, 'exotic racks increase specialty storage');
delete player.organelles.exotic_vacuole;

// Anaerobic processor should produce net ATP from biomass at rest.
player.cargo.energy = 1;
player.cargo.biomass = K.__test.caps(player).biomass;
const e0 = player.cargo.energy;
for (let i = 0; i < 240; i++) K.step(world, {}, 1 / 60);
player = K.getPlayer(world);
assert(player.cargo.energy > e0 + 0.15, `anaerobic processor should net ATP; got ${player.cargo.energy} from ${e0}`);
assert(player.cargo.biomass < K.__test.caps(player).biomass, 'anaerobic processor consumes biomass');

// Feeding action is generated by graph organelles, not hard-coded starter privilege.
let actions = K.getAvailableActions(world);
assert(actions.some(a => a.id === 'feed'), 'feed action appears from membrane intake');
player.organelles.membrane_intake = 0;
player.organelles.cytostome = 0;
actions = K.getAvailableActions(world);
assert(!actions.some(a => a.id === 'feed'), 'feed action disappears without intake organs');
player.organelles.membrane_intake = 1;

// Storage/exotic/membrane/buoyancy offerings exist and separate buoyancy resource is gone.
const offers = K.getYukiOfferings(world);
assert(offers.some(o => o.id === 'membrane_hardening'), 'membrane hardening is buyable');
assert(offers.some(o => o.id === 'anaerobic_processor'), 'anaerobic processor is buyable');
assert(offers.some(o => o.id === 'oxygen_vacuole'), 'oxygen buoyancy vacuole is buyable');
assert(!offers.some(o => o.id === 'buoyancy_vacuole'), 'separate buoyancy organ removed');

// Hardening changes membrane physics.
const por0 = K.__test.membranePorosity(player);
const hard0 = K.__test.membraneHardness(player);
player.organelles.membrane_hardening = 2;
assert(K.__test.membranePorosity(player) < por0, 'hardening lowers permeability');
assert(K.__test.membraneHardness(player) > hard0, 'hardening raises membrane hardness');

// Oxygen vacuole converts internal oxygen into lift.
const b0 = K.__test.buoyancy(player);
player.organelles.oxygen_vacuole = 2;
player.oxygen = 0.85;
assert(K.__test.buoyancy(player) > b0 + 40, 'oxygen vacuoles convert internal oxygen into lift');

// One purchased flagellum means one count.
player.cargo.biomass = 99; player.cargo.lipids = 99; player.cargo.spores = 1; player.cargo.enzymes = 1; player.cargo.crystals = 1; player.cargo.energy = 99;
const beforeFlagella = player.organelles.flagella || 0;
const buyFlag = K.buyOffering(world, 'flagella');
assert(buyFlag.ok, `flagellum should be buyable: ${buyFlag.reason || ''}`);
assert((player.organelles.flagella || 0) === beforeFlagella + 1, 'buying one flagellum adds one flagellum');

// Radius grows with organs and fullness.
const r0 = player.r;
player.organelles.storage_vacuole = 2;
player.cargo.biomass = K.__test.caps(player).biomass;
player.cargo.lipids = K.__test.caps(player).lipids;
player.cargo.energy = K.__test.caps(player).energy;
K.step(world, {}, 1 / 60);
assert(K.getPlayer(world).r > r0 + 3, 'body inflates with organelles and full tanks');

const hud = K.getHudProjection(world);
assert(res(hud, 'energy').label === 'ATP', 'energy resource is labeled ATP');
console.log('MOBILE_V1_3_0_GRAPH_PURITY_SMOKE_OK');
